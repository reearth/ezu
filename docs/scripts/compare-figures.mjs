// Side-by-side figures for the MapLibre compatibility pages: the same tile
// rendered by ezu from a translated recipe, and by maplibre-gl-js.
//
//   npm run compare
//
// Runs `ezu-compare`, which converts the style, renders it in-process, renders
// the reference through `tools/mlgl-ref` (maplibre-gl-js in headless Chromium),
// and reports SSIM. The images and the measured numbers land together in
// `src/content/docs/maplibre/_comparison.mdx`, so the figure captions cannot
// claim a similarity the images do not have.
//
// Prerequisites, and why this is not a CI step:
//
//   cargo build --release -p ezu-compare
//   cd tools/mlgl-ref && npm install && npx playwright install chromium
//
// Output is committed.

import { execFile } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import sharp from 'sharp';

const run = promisify(execFile);
const DOCS = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(DOCS, '..');
const OUT = join(DOCS, 'public/figures');
const WORK = join(REPO, 'target/doc-compare');

/**
 * A full Protomaps theme served by reearth-papers: 68 layers, 11 of them
 * `symbol`, with its own glyph endpoint — so the comparison covers text and
 * icons rather than just fills and lines.
 */
const STYLE = 'https://papers.reearth.land/styles/protomaps-light/style.json';

const TILES = [
  { tile: '14/14550/6452', place: 'Shibuya and Aoyama at z14 — dense labels, icons, park fills' },
  { tile: '12/3637/1613', place: 'Greater Tokyo at z12 — coastline, motorways, sparse labels' },
  { tile: '15/29101/12904', place: 'A single Tokyo neighbourhood at z15 — street names and building fills' },
];

const OUT_WIDTH = 512;

async function publish(src, name) {
  await sharp(src).resize(OUT_WIDTH).webp({ quality: 84 }).toFile(join(OUT, `${name}.webp`));
}

function parseScores(stdout) {
  // The table rows read: `14/14550/6452  94.90  0.800   13.007   8.15%   163  …`
  const scores = new Map();
  for (const line of stdout.split('\n')) {
    const m = line.match(/^(\d+\/\d+\/\d+)\s+([\d.]+)\s+([\d.]+)/);
    if (m) scores.set(m[1], { score: m[2], ssim: m[3] });
  }
  return scores;
}

async function main() {
  mkdirSync(OUT, { recursive: true });
  mkdirSync(WORK, { recursive: true });

  const { stdout } = await run(
    'cargo',
    [
      'run',
      '--release',
      '--quiet',
      '-p',
      'ezu-compare',
      '--',
      '--style',
      STYLE,
      '--tiles',
      TILES.map((t) => t.tile).join(','),
      '--out',
      WORK,
    ],
    { cwd: REPO, maxBuffer: 32 * 1024 * 1024 }
  );
  process.stdout.write(stdout);

  const scores = parseScores(stdout);
  const blocks = [];

  for (const { tile, place } of TILES) {
    const slug = tile.replace(/\//g, '-');
    const stem = join(WORK, tile.replace(/\//g, '_'));
    await publish(`${stem}.ezu.png`, `compare-${slug}-ezu`);
    await publish(`${stem}.ref.png`, `compare-${slug}-mlgl`);

    const s = scores.get(tile);
    const caption = [
      `${place}.`,
      s ? `SSIM <strong>${s.ssim}</strong>, closeness score ${s.score}/100.` : '',
    ]
      .filter(Boolean)
      .join(' ');

    blocks.push(
      [
        `<figure class="page-fig page-fig--pair">`,
        `  <div class="page-fig__images">`,
        `    <img src="/ezu/figures/compare-${slug}-ezu.webp" alt="Tile ${tile} rendered by ezu" width="512" height="512" loading="lazy" decoding="async" />`,
        `    <img src="/ezu/figures/compare-${slug}-mlgl.webp" alt="The same tile rendered by maplibre-gl-js" width="512" height="512" loading="lazy" decoding="async" />`,
        `  </div>`,
        `  <figcaption>ezu (left) and maplibre-gl-js (right). ${caption}</figcaption>`,
        `</figure>`,
        '',
      ].join('\n')
    );
  }

  // The style's own layer count, so the partial can say what was converted.
  const styleJson = JSON.parse(readFileSync(join(WORK, '_style.json'), 'utf8'));
  const symbols = styleJson.layers.filter((l) => l.type === 'symbol').length;

  const partial = [
    '{/* Generated by docs/scripts/compare-figures.mjs — do not edit. */}',
    '',
    `Every pair below is one XYZ tile of [\`protomaps-light\`](${STYLE}) —`,
    `${styleJson.layers.length} layers, ${symbols} of them \`symbol\` — converted with`,
    '`ezu translate` and rendered by ezu on the CPU, next to the same tile drawn by',
    'maplibre-gl-js on a GPU (headless Chromium, software WebGL). Nothing is',
    'hand-tuned between them: same style, same data, same tile.',
    '',
    ...blocks,
    'SSIM is structural similarity over 8×8 luma windows, which is less dominated by',
    'antialiasing and label noise than a plain pixel difference. Reproduce any of these',
    'with `ezu-compare`:',
    '',
    '```sh',
    'cargo run --release -p ezu-compare -- \\',
    `  --style ${STYLE} \\`,
    `  --tiles ${TILES.map((t) => t.tile).join(',')} \\`,
    '  --out out/compare',
    '```',
    '',
  ].join('\n');

  const path = join(DOCS, 'src/content/docs/maplibre/_comparison.mdx');
  writeFileSync(path, partial);
  console.log(`\nwrote ${TILES.length} comparison figures and ${path}`);
}

main();
